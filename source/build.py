#!/usr/bin/env python3
"""Assemble dist/index.html from src/.

    src/shell_top.html        <!doctype> .. <body> markup (styles + embedded webfonts)
    src/app/00_*.js           instrument header (versions)
    src/webgazer.bundle.js    WebGazer 3.5.3, verbatim
    src/app/[10-99]_*.js      instrument modules, concatenated in filename order

Run:  python3 build.py              (writes dist/index.html, copies admin.html, data dictionary)
      python3 build.py --release    (also keeps a copy in releases/<version>.html)
      python3 build.py --out <dir>  (write the site somewhere else, e.g. the GitHub Pages root)
"""
import pathlib, re, shutil, sys, hashlib, json, csv

ROOT = pathlib.Path(__file__).resolve().parent
SRC, DIST = ROOT / "src", ROOT / "dist"
if "--out" in sys.argv:
    DIST = pathlib.Path(sys.argv[sys.argv.index("--out") + 1]).resolve()
    DIST.mkdir(parents=True, exist_ok=True)

def main():
    app = sorted((SRC / "app").glob("*.js"))
    head = [p for p in app if p.name.startswith("00_")]
    rest = [p for p in app if not p.name.startswith("00_")]
    parts = [(SRC / "shell_top.html").read_text(), "<script>\n"]
    parts += [p.read_text() for p in head]
    parts.append((SRC / "webgazer.bundle.js").read_text())
    # The data dictionary is one JSON source: embedded in the instrument (it
    # ships inside every session folder) and written beside the build.
    dd = json.loads((SRC / "data_dictionary.json").read_text())
    gen = "\n/* generated by build.py from src/data_dictionary.json */\nconst DATA_DICTIONARY = " + json.dumps(dd, ensure_ascii=False) + ";\n"
    for p in rest:
        if p.name.startswith("60_"):
            parts.append(gen)
        parts.append(p.read_text())
    parts.append("</script>\n</body>\n</html>\n")
    with open(DIST / "DATA_DICTIONARY.csv", "w", newline="") as fh:
        w = csv.writer(fh); w.writerow(["file", "column", "type", "unit", "description"])
        for row in dd["columns"]: w.writerow(row)
        for f, d in dd["files"]: w.writerow([f, "(file)", "", "", d])
    html = "".join(parts)
    out = DIST / "index.html"
    out.write_text(html)
    ver = re.search(r'INSTRUMENT_VERSION = "([^"]+)"', html).group(1)
    print(f"built {out}  {len(html)/1e6:.2f} MB  {ver}  sha256 {hashlib.sha256(html.encode()).hexdigest()[:16]}")
    for extra in ["admin.html"]:
        if (SRC / extra).exists():
            shutil.copy(SRC / extra, DIST / extra)
            print("copied", extra)
    if "--release" in sys.argv:
        rel = ROOT / "releases"; rel.mkdir(exist_ok=True)
        shutil.copy(out, rel / f"{ver}.html")
        print("release copy", rel / f"{ver}.html")

if __name__ == "__main__":
    main()
