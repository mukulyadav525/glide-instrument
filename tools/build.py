#!/usr/bin/env python3
"""Build the three GLIDE pages from src/ into the repository root (the GitHub Pages site).

    src/participant/shell.html     page markup and styles for the participant laptop
    src/participant/00_*.js        versions (go before WebGazer)
    src/shared/*.js                code used by both the participant page and the educator portal
    src/vendor/webgazer.bundle.js  WebGazer 3.5.3, verbatim
    src/participant/[10-99]_*.js   instrument modules, concatenated in filename order
    src/educator/educator.html     educator portal (gets the instrument's panel styles injected)
    src/admin/admin.html           admin console (copied)
    src/data_dictionary.json       single source for DATA_DICTIONARY.csv and the embedded copy

Run from anywhere:
    python3 tools/build.py              write index.html, educator.html, admin.html, DATA_DICTIONARY.csv to the repo root
    python3 tools/build.py --out DIR    write them somewhere else
    python3 tools/build.py --release    also freeze releases/<version>.html
    python3 tools/build.py --check      build to a temporary folder and fail if the committed pages are out of date (CI)
"""
import csv, hashlib, io, json, pathlib, re, shutil, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
PAGES = ["index.html", "educator.html", "admin.html", "DATA_DICTIONARY.csv"]


def participant_css(shell):
    """The instrument's own style block (the second <style>; the first holds the base64 fonts)."""
    blocks = re.findall(r"<style>(.*?)</style>", shell, re.S)
    return blocks[-1]


def build(out):
    out.mkdir(parents=True, exist_ok=True)
    part = SRC / "participant"
    mods = sorted(part.glob("*.js"))
    head = [p for p in mods if p.name.startswith("00_")]
    rest = [p for p in mods if not p.name.startswith("00_")]
    shell = (part / "shell.html").read_text()
    dd = json.loads((SRC / "data_dictionary.json").read_text())
    gen = "\n/* generated by tools/build.py from src/data_dictionary.json */\nconst DATA_DICTIONARY = " + json.dumps(dd, ensure_ascii=False) + ";\n"

    shared = sorted((SRC / "shared").glob("*.js"))
    parts = [shell, "<script>\n"] + [p.read_text() for p in head] + [p.read_text() for p in shared]
    parts.append((SRC / "vendor" / "webgazer.bundle.js").read_text())
    for p in rest:
        if p.name.startswith("60_"):
            parts.append(gen)
        parts.append(p.read_text())
    parts.append("</script>\n</body>\n</html>\n")
    html = "".join(parts)
    (out / "index.html").write_text(html)
    ver = re.search(r'INSTRUMENT_VERSION = "([^"]+)"', html).group(1)
    print(f"built index.html     {len(html)/1e6:.2f} MB  {ver}  sha256 {hashlib.sha256(html.encode()).hexdigest()[:16]}")

    edu = (SRC / "educator" / "educator.html").read_text()
    edu = (edu.replace("/*__INSTRUMENT_CSS__*/", participant_css(shell))
              .replace("/*__SHARED_JS__*/", "\n".join(p.read_text() for p in shared))
              .replace("__INSTRUMENT_VERSION__", ver))
    (out / "educator.html").write_text(edu)
    print(f"built educator.html  {len(edu)/1e3:.0f} kB")

    shutil.copy(SRC / "admin" / "admin.html", out / "admin.html")
    print("copied admin.html")

    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\r\n")
    w.writerow(["file", "column", "type", "unit", "description"])
    for row in dd["columns"]: w.writerow(row)
    for f, d in dd["files"]: w.writerow([f, "(file)", "", "", d])
    (out / "DATA_DICTIONARY.csv").write_text(buf.getvalue())
    return ver


def main():
    if "--check" in sys.argv:
        with tempfile.TemporaryDirectory() as t:
            build(pathlib.Path(t))
            stale = [p for p in PAGES if not (ROOT / p).exists() or (ROOT / p).read_bytes() != (pathlib.Path(t) / p).read_bytes()]
        if stale:
            print("OUT OF DATE (run python3 tools/build.py and commit):", ", ".join(stale)); sys.exit(1)
        print("built pages match the source"); return
    out = pathlib.Path(sys.argv[sys.argv.index("--out") + 1]).resolve() if "--out" in sys.argv else ROOT
    ver = build(out)
    if "--release" in sys.argv:
        rel = ROOT / "releases"; rel.mkdir(exist_ok=True)
        shutil.copy(out / "index.html", rel / f"{ver}.html")
        print("release copy", rel / f"{ver}.html")


if __name__ == "__main__":
    main()
